//! World sources: pure functions from a chunk coordinate to that chunk's voxels, and a wrapper
//! that writes prefabs over another source's chunks.

use std::sync::Arc;

use crate::brick::Brick;
use crate::chunk::Chunk;
use crate::coords::{CHUNK_BRICKS, ChunkCoord, VoxelCoord};
use crate::material::MaterialId;
use crate::prefab::{Prefab, Rot};
use crate::stamp::{blit_into, voxel_box};

/// Produces the voxels of one chunk. Implementations must be pure functions of `coord` (and
/// their own fields, such as a seed), because chunks are generated in parallel in any order.
///
/// `out` arrives as all air with every slot dirty.
pub trait WorldSource {
    fn chunk(&self, coord: ChunkCoord, out: &mut Chunk);
}

/// Every voxel is one material.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct UniformSource(pub MaterialId);

impl WorldSource for UniformSource {
    fn chunk(&self, _coord: ChunkCoord, out: &mut Chunk) {
        for slot in 0..CHUNK_BRICKS {
            out.set_brick(slot, Brick::Uniform(self.0));
        }
    }
}

/// A source whose chunks are `base`'s with prefabs written over them: generation-time
/// placement. Each prefab is rotated once, at construction, and keeps its voxel box; a chunk
/// is generated by `base` and then every placement whose box meets it is written into it, in
/// placement order, so a later placement wins where two overlap. Like
/// [`crate::World::stamp`], a placement writes every masked voxel whatever the material
/// flags. A placement reaching past the generated extent is clipped by it: each chunk takes
/// only the voxels inside it.
#[derive(Clone, Debug)]
pub struct StampedSource<S> {
    base: S,
    /// Rotated prefab and its inclusive voxel box, minimum corner first.
    placed: Vec<(Prefab, [i64; 3], [i64; 3])>,
}

impl<S> StampedSource<S> {
    /// `base` with `placements` written over it, each as (prefab, minimum corner of the
    /// rotated prefab, rotation). Empty prefabs are dropped.
    pub fn new(base: S, placements: Vec<(Arc<Prefab>, VoxelCoord, Rot)>) -> Self {
        let placed = placements
            .into_iter()
            .filter_map(|(prefab, origin, rot)| {
                let p = prefab.rotated(rot);
                let (lo, hi) = voxel_box(origin, p.size())?;
                Some((p, lo, hi))
            })
            .collect();
        Self { base, placed }
    }

    pub fn base(&self) -> &S {
        &self.base
    }

    /// Placements kept: the inclusive voxel box of each rotated prefab, in placement order.
    pub fn boxes(&self) -> impl Iterator<Item = (VoxelCoord, VoxelCoord)> + '_ {
        let to =
            |v: [i64; 3]| VoxelCoord(v.map(|c| c.clamp(i32::MIN.into(), i32::MAX.into()) as i32));
        self.placed
            .iter()
            .map(move |(_, lo, hi)| (to(*lo), to(*hi)))
    }
}

impl<S: WorldSource> WorldSource for StampedSource<S> {
    fn chunk(&self, coord: ChunkCoord, out: &mut Chunk) {
        self.base.chunk(coord, out);
        for (p, lo, hi) in &self.placed {
            blit_into(out, coord, p, *lo, *hi);
        }
    }
}
